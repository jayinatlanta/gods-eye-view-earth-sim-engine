/**
 * Returns all active rapid transit route objects for a given city ID.
 */
export function getCityMetroRoutes(cityId) {
  const lineKeys = METRO_NETWORKS_BY_CITY[cityId] || [];
  if (lineKeys.length === 0) {
    const single = Object.values(RAPID_TRANSIT_ROUTES).find(
      (r) => r.cityId === cityId,
    );
    return single ? [single] : [RAPID_TRANSIT_ROUTES.chicago_cta_loop];
  }
  return lineKeys.map((k) => RAPID_TRANSIT_ROUTES[k]).filter(Boolean);
}

function parkStop({
  id,
  name,
  lat,
  lon,
  elev,
  category,
  land,
  estimatedWaitMin,
  snackNote,
  wikiTitle,
  youtubeSearchQuery,
  youtubeVideoId = null,
  streetBearingDeg = 0,
  icon = '🎢',
  lore,
  companionNote,
  showcaseZone = null,
}) {
  return {
    id,
    name,
    lat,
    lon,
    elev,
    category,
    land,
    estimatedWaitMin,
    waitTimeMin: estimatedWaitMin,
    snackNote,
    snackTag: snackNote,
    wikiTitle,
    ...(youtubeVideoId ? { youtubeVideoId } : {}),
    youtubeSearchQuery,
    streetBearingDeg,
    icon,
    lore,
    companionNote,
    ...(showcaseZone ? { showcaseZone, dayChapter: showcaseZone } : {}),
  };
}


function buildResortSecrets(resortId, stops, specs) {
  return specs.map((spec, idx) => {
    const anchor = stops[spec.stopIdx % stops.length] || stops[0];
    const pos = offsetLatLonByMeters(
      anchor.lat,
      anchor.lon,
      spec.bearingDeg,
      spec.distanceMeters,
    );
    return {
      id: `${resortId}_secret_${idx + 1}`,
      title: spec.title,
      icon: spec.icon || '🌴',
      hint: spec.hint,
      story: spec.story,
      lat: pos.lat,
      lon: pos.lon,
      elev: anchor.elev || 20,
      land: anchor.land || spec.land || '',
      kind: 'resort_secret',
    };
  });
}


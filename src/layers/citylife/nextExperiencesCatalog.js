export function isNextExperienceId(cityId) {
  const key = String(cityId || '')
    .trim()
    .toLowerCase();
  if (!key) return false;
  return Boolean(
    NEXT_EXPERIENCE_METADATA[key] ||
    NEXT_EXPERIENCE_METADATA[NEXT_EXPERIENCE_ALIASES[key]],
  );
}

export function getNextExperienceBridgesForVenue(venueId) {
  const raw = String(venueId || '')
    .trim()
    .toLowerCase();
  const key = NEXT_EXPERIENCE_ALIASES[raw] || raw;
  if (!key) return [];
  return NEXT_EXPERIENCE_BRIDGES.filter((b) => b.fromCityId === key).map(
    (b) => ({ ...b }),
  );
}

export function getEveningAnchorForNextExperience(
  venueId,
  fallbackStop = null,
) {
  const raw = String(venueId || '')
    .trim()
    .toLowerCase();
  const key = NEXT_EXPERIENCE_ALIASES[raw] || raw;
  if (key && NEXT_EXPERIENCE_EVENING_ANCHORS[key]) {
    return { ...NEXT_EXPERIENCE_EVENING_ANCHORS[key] };
  }
  if (
    fallbackStop &&
    Number.isFinite(fallbackStop.lat) &&
    Number.isFinite(fallbackStop.lon)
  ) {
    return {
      id: key || 'experience',
      iconName: fallbackStop.name || 'Evening Overlook',
      lat: fallbackStop.lat,
      lon: fallbackStop.lon,
      elev: fallbackStop.elev || 32,
      burstAltitudeM: 22,
      defaultMode: 'fire_pit_lounge',
      colors: ['#f59e0b', '#fb923c', '#fde047', '#ef4444'],
    };
  }
  return null;
}
